let current = 'es';

function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'es';
  document.documentElement.lang = current;
  applyStatic();
}

/** t('rooms.summary', { players: 10, rooms: 3 }) */
function t(key, vars) {
  let text = (STRINGS[current] && STRINGS[current][key]) || STRINGS.es[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/**
 * Resuelve todo lo marcado con data-i18n en el HTML.
 *
 * El icono se salva. `textContent = …` borra los hijos, así que un botón con su
 * dibujo adelante se quedaba sin él en el primer repintado —o sea, en el
 * arranque, porque `setLanguage` pasa por acá—. Se reescribe sólo el texto y se
 * vuelve a poner el icono delante, que es el orden en el que está en el HTML.
 *
 * El `ⓘ` de las filas de ajuste se salva por lo mismo y por el otro lado: va
 * DESPUÉS del texto, que es donde está escrito en el HTML.
 */
function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const icon = el.querySelector(':scope > svg[data-icon]');
    const hint = el.querySelector(':scope > i.hint');
    if (icon || hint) {
      const partes = [];
      if (icon) partes.push(icon);
      partes.push(document.createTextNode(t(el.dataset.i18n)));
      if (hint) partes.push(hint);
      el.replaceChildren(...partes);
    } else {
      el.textContent = t(el.dataset.i18n);
    }
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
  }
  /*
   * El texto del `ⓘ` se resuelve acá y se deja escrito en el propio elemento.
   * No es sólo comodidad: el buscador del panel mira lo que dice cada fila
   * INCLUYENDO su explicación larga, y leerla implicaría llamar a `t()` una vez
   * por `ⓘ` en cada tecla que se aprieta.
   */
  for (const el of root.querySelectorAll('[data-hint]')) {
    el.dataset.hintText = t(el.dataset.hint);
  }
}

window.i18n = { t, setLanguage, applyStatic, get language() { return current; } };

